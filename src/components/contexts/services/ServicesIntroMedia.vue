<script setup>
import { useMainStore } from '@/stores/main';
import ScrollTrigger from 'gsap/ScrollTrigger'
import { DrawSVGPlugin } from 'gsap/DrawSVGPlugin'

const { $gsap: gsap } = useNuxtApp()
const store = useMainStore()
const slide = ref(null)
watch(
    () => store.ready,
    async (loaded) => {
        await nextTick()
        if (!loaded) return
        gsap.registerPlugin(ScrollTrigger);
        gsap.registerPlugin(DrawSVGPlugin);
        AnimationFrame(anim(), 1000)
    })

onMounted(async () => {
    await nextTick()
    if (!store.ready) return
    gsap.registerPlugin(ScrollTrigger);
    gsap.registerPlugin(DrawSVGPlugin);
    AnimationFrame(anim(), 1000)
})
const anim = () => {
    const tl = gsap.timeline({ paused: true });

    const slideEl = slide.value
    gsap.set("#servicesEditingFilm", {
        autoAlpha: 0,
        rotation: 4,
        transformOrigin: "50% 50%"
    });
    gsap.set("#servicesEditingSoundTracker", {
        autoAlpha: 0
    });

    tl
        .from("#servicesEditingOutline", {
            drawSVG: "0%",
            duration: 1
        })
        .from("#servicesEditingSoundBG", {
            scaleX: 0,
            transformOrigin: "left center",
            ease: "power2.out",
            duration: 0.8
        }, "-=0.5")
        .from("#servicesEditingSoundWave path", {
            scaleY: 0,
            transformOrigin: "50% 50%",
            ease: "power1.out",
            duration: 0.6,
            stagger: 0.02
        }, "-=0.4")
        .to("#servicesEditingSoundTracker", {
            autoAlpha: 1,
            x: "420",
            ease: "power1.inOut",
            duration: 8
        }, "-=2")

        .to("#servicesEditingFilm", {
            autoAlpha: 1,
            x: "90%",
            ease: "power1.out",
            duration: 4
        }, "-=5");
    tl.play()
    ScrollTrigger.create({
        trigger: slideEl,
        start: "top 80%",
        end: "bottom 20%",
        onEnter: () => tl.play(),
        onLeave: () => tl.tweenTo(0, {
            duration: 0.2,
            onComplete: () => tl.pause()
        }),
        onEnterBack: () => tl.play(),
        onLeaveBack: () => tl.tweenTo(0, {
            duration: 0.2,
            onComplete: () => tl.pause()
        })
    });
}

